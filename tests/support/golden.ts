// Shared golden-file plumbing for presentation snapshot tests.
//
// A golden file is a list of `=== key ===` sections. Tests compare each section
// they render; `UPDATE_GOLDEN=1 npm test` rewrites the files instead.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import type { BoxTheme } from "../../extension-src/omp-theme/shared/box.js";

export const UPDATE_GOLDEN = process.env.UPDATE_GOLDEN === "1";

// Pi's ThemeColor tokens. A token's index is its SGR colour number, so the
// encoding survives refactors that reorder theme calls; an unknown token fails.
const THEME_TOKENS = [
	"accent", "border", "borderAccent", "borderMuted", "success", "error", "warning", "muted", "dim", "text",
	"thinkingText", "scrollbarTrack", "scrollbarThumb", "searchMatchText", "userMessageText", "customMessageText",
	"customMessageLabel", "toolTitle", "toolOutput", "mdHeading", "mdLink", "mdLinkUrl", "mdCode", "mdCodeBlock",
	"mdCodeBlockBorder", "mdQuote", "mdQuoteBorder", "mdHr", "mdListBullet", "toolDiffAdded", "toolDiffRemoved",
	"toolDiffContext", "syntaxComment", "syntaxKeyword", "syntaxFunction", "syntaxVariable", "syntaxString",
	"syntaxNumber", "syntaxType", "syntaxOperator", "syntaxPunctuation", "thinkingOff", "thinkingMinimal",
	"thinkingLow", "thinkingMedium", "thinkingHigh", "thinkingXhigh", "thinkingMax", "bashMode",
] as const;

/** A theme whose every style is a reversible SGR, so goldens can spell it out. */
export const goldenTheme: BoxTheme = {
	fg(color, text) {
		const index = THEME_TOKENS.indexOf(color as (typeof THEME_TOKENS)[number]);
		if (index < 0) throw new Error(`unknown theme token: ${color}`);
		return `\x1b[38;5;${index}m${text}\x1b[39m`;
	},
	bold: (text) => `\x1b[1m${text}\x1b[22m`,
	italic: (text) => `\x1b[3m${text}\x1b[23m`,
	inverse: (text) => `\x1b[7m${text}\x1b[27m`,
	getColorMode: () => "truecolor",
};

const SGR_NAMES: Readonly<Record<string, string>> = {
	"39": "/",
	"1": "b",
	"22": "/b",
	"3": "i",
	"23": "/i",
	"7": "inv",
	"27": "/inv",
	"2": "faint",
};

/** Spell out theme tokens, attributes and other escapes of a rendered line. */
export function styledLine(line: string): string {
	return line
		.replace(/\x1b\]([^\x07\x1b]*)(?:\x07|\x1b\\)/g, (_match, body: string) => `{osc:${body}}`)
		.replace(/\x1b\[([0-9;]*)m/g, (_match, params: string) => {
			const token = /^38;5;(\d+)$/.exec(params);
			if (token) return `{${THEME_TOKENS[Number(token[1])] ?? `color${token[1]}`}}`;
			return `{${SGR_NAMES[params] ?? `sgr:${params}`}}`;
		})
		.replace(/\x1b/g, "{esc}");
}

/** Plain text of a rendered line (escapes removed). */
export function plainLine(line: string): string {
	return line.replace(/\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)/g, "").replace(/\x1b\[[0-9;]*m/g, "");
}

/** Layout form: plain text with `¶` marking the end of every line. */
export function layoutOf(lines: readonly string[]): string {
	return lines.map((line) => `${plainLine(line)}¶`).join("\n");
}

const HEADER_PREFIX = "=== ";
const HEADER_SUFFIX = " ===";

export function readGoldenSections(file: string): Map<string, string> {
	const sections = new Map<string, string>();
	if (!existsSync(file)) return sections;
	let key: string | undefined;
	let body: string[] = [];
	const flush = () => {
		if (key !== undefined) sections.set(key, body.join("\n").replace(/\n+$/, ""));
	};
	for (const line of readFileSync(file, "utf8").replace(/\r/g, "").split("\n")) {
		if (line.startsWith(HEADER_PREFIX) && line.endsWith(HEADER_SUFFIX)) {
			flush();
			key = line.slice(HEADER_PREFIX.length, -HEADER_SUFFIX.length);
			body = [];
		} else if (key !== undefined) body.push(line);
	}
	flush();
	return sections;
}

export function writeGoldenSections(file: string, title: string, source: string, sections: Map<string, string>): void {
	mkdirSync(dirname(file), { recursive: true });
	const parts = [`# ${title}`, `# Generated by ${source} — UPDATE_GOLDEN=1 npm test`, ""];
	for (const [key, value] of sections) parts.push(`${HEADER_PREFIX}${key}${HEADER_SUFFIX}`, value, "");
	writeFileSync(file, parts.join("\n"));
}
